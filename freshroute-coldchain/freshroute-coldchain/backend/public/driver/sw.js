// Service worker: makes the app SHELL load with no network (airplane mode).
// API calls are never intercepted: the app handles those itself (localStorage cache + outbox).
const CACHE = 'freshroute-driver-v1';
const SHELL = ['/driver/', '/driver/app.js', '/driver/queue.js', '/driver/style.css', '/driver/manifest.webmanifest', '/driver/icon.svg'];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

// Network-first (so code updates arrive when online), cache fallback (so it works offline).
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith('/driver/')) return;
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
        return res;
      })
      .catch(() => caches.match(e.request).then((hit) => hit || caches.match('/driver/'))),
  );
});
